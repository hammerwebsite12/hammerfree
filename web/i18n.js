const I18N_LANG_NAMES = {
  en: "English",
  zh: "中文 (Chinese)",
  es: "Español (Spanish)",
  tl: "Tagalog",
};

let I18N_CURRENT = "en";

function i18nSetLang(lang) {
  I18N_CURRENT = I18N_STRINGS[lang] ? lang : "en";
}

function i18nGetLang() {
  return I18N_CURRENT;
}

function t(key, params) {
  const table = I18N_STRINGS[I18N_CURRENT] || I18N_STRINGS.en;
  let str = table[key];
  if (str === undefined) str = I18N_STRINGS.en[key];
  if (str === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.documentElement.lang = I18N_CURRENT;
}
